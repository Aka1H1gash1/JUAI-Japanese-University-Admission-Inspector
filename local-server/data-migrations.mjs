import { randomUUID } from 'node:crypto';

import { tagImportedTasks } from './planning-fields.mjs';

/**
 * 数据迁移工具函数
 * 用于支持版本控制、日程同步等新特性
 */

/**
 * Migration 14: 添加版本控制字段
 * 为研究室日程、材料待办、专攻考试历史添加版本号
 */
export function addVersionControl(data) {
  // 为所有研究室的日程添加版本号
  for (const lab of data.labs ?? []) {
    if (lab.timeline && lab.timeline.version === undefined) {
      lab.timeline.version = 0;
    }

    // 为材料待办添加版本号（存储在lab层级）
    if (lab.tasks && lab.tasksVersion === undefined) {
      lab.tasksVersion = 0;
    }
  }

  // 为专攻考试历史添加版本号
  for (const major of data.majors ?? []) {
    if (major.examHistory && major.examHistoryVersion === undefined) {
      major.examHistoryVersion = 0;
    }
  }

  return data;
}

/**
 * Migration 15: 初始化日程来源标记
 * 为现有日程事件标记为手动创建，并初始化自动同步开关
 */
export function initializeTimelineSources(data) {
  for (const lab of data.labs ?? []) {
    if (!lab.timeline) continue;

    // 为现有日程事件添加来源标记
    for (const event of lab.timeline.events ?? []) {
      if (event.autoGenerated === undefined) {
        // 现有事件默认为手动创建
        event.autoGenerated = false;
        event.syncEnabled = true;
      }
      // 初始化 sourceId 字段
      if (event.sourceId === undefined) {
        event.sourceId = '';
      }
    }

    // 初始化自动同步开关（默认启用）
    if (lab.timeline.autoSyncExams === undefined) {
      lab.timeline.autoSyncExams = true;
    }
  }

  return data;
}

/**
 * Migration 16: 初始化分析历史字段
 * 为专攻添加 analysisHistory 字段用于追溯募集要项分析来源
 */
export function initializeAnalysisHistory(data) {
  for (const major of data.majors ?? []) {
    if (major.analysisHistory === undefined) {
      major.analysisHistory = [];
    }
  }

  return data;
}

/**
 * 从专攻考试历史生成研究室日程事件
 * 这是自动同步机制的核心函数
 */
export function syncExamsToTimeline(data, labId, majorId) {
  const lab = data.labs?.find((item) => item.id === labId);
  const major = data.majors?.find((item) => item.id === majorId);

  if (!lab || !major || !lab.timeline) return data;

  // 如果禁用了自动同步，直接返回
  if (lab.timeline.autoSyncExams === false) return data;

  const timeline = lab.timeline;
  const examHistory = major.examHistory ?? [];

  // 收集现有的自动生成事件的 sourceId
  const existingSourceIds = new Set(
    timeline.events
      .filter((e) => e.autoGenerated && e.sourceId)
      .map((e) => e.sourceId),
  );

  // 收集用户手动覆盖的 sourceId
  const replacedSourceIds = new Set(
    timeline.events
      .filter((e) => !e.autoGenerated && e.replaces)
      .map((e) => e.replaces),
  );

  // 为每个考试记录生成对应的日程事件
  for (const exam of examHistory) {
    const examSourcePrefix = `major:${majorId}:exam:${exam.id}`;

    // 生成出愿日程（如果有出愿时间）
    if (major.applicationStart || major.applicationEnd) {
      const sourceId = `${examSourcePrefix}:application`;
      const replaced = replacedSourceIds.has(sourceId);

      if (!replaced && !existingSourceIds.has(sourceId)) {
        const start = major.applicationStart?.match(/^\d{4}-\d{2}-\d{2}$/)
          ? major.applicationStart
          : major.applicationEnd?.match(/^\d{4}-\d{2}-\d{2}$/)
            ? major.applicationEnd
            : null;
        const end = major.applicationEnd?.match(/^\d{4}-\d{2}-\d{2}$/)
          ? major.applicationEnd
          : start;

        if (start && end) {
          timeline.events.push({
            id: randomUUID(),
            kind: 'application',
            title: `${exam.year} 年${exam.session ? ` ${exam.session}` : ''} 出愿`,
            start,
            end,
            at: '',
            endAt: '',
            complete: false,
            notes: '自动同步自专攻考试历史',
            replaces: '',
            sourceId,
            autoGenerated: true,
            syncEnabled: true,
            linkContact: false,
          });
        }
      }
    }

    // 生成笔试日程
    if (exam.writtenDate?.match(/^\d{4}-\d{2}-\d{2}$/)) {
      const sourceId = `${examSourcePrefix}:written`;
      const replaced = replacedSourceIds.has(sourceId);

      if (!replaced && !existingSourceIds.has(sourceId)) {
        timeline.events.push({
          id: randomUUID(),
          kind: 'written',
          title: `${exam.year} 年${exam.session ? ` ${exam.session}` : ''} 笔试`,
          start: exam.writtenDate,
          end: exam.writtenDate,
          at: '',
          endAt: '',
          complete: false,
          notes: exam.subjects
            ? `科目：${exam.subjects}\n自动同步自专攻考试历史`
            : '自动同步自专攻考试历史',
          replaces: '',
          sourceId,
          autoGenerated: true,
          syncEnabled: true,
          linkContact: false,
        });
      }
    }

    // 生成面试日程
    if (exam.interviewDate?.match(/^\d{4}-\d{2}-\d{2}$/)) {
      const sourceId = `${examSourcePrefix}:interview`;
      const replaced = replacedSourceIds.has(sourceId);

      if (!replaced && !existingSourceIds.has(sourceId)) {
        timeline.events.push({
          id: randomUUID(),
          kind: 'interview',
          title: `${exam.year} 年${exam.session ? ` ${exam.session}` : ''} 面试`,
          start: exam.interviewDate,
          end: exam.interviewDate,
          at: '',
          endAt: '',
          complete: false,
          notes: '自动同步自专攻考试历史',
          replaces: '',
          sourceId,
          autoGenerated: true,
          syncEnabled: true,
          linkContact: false,
        });
      }
    }

    // 生成放榜日程
    if (exam.resultDate?.match(/^\d{4}-\d{2}-\d{2}$/)) {
      const sourceId = `${examSourcePrefix}:result`;
      const replaced = replacedSourceIds.has(sourceId);

      if (!replaced && !existingSourceIds.has(sourceId)) {
        timeline.events.push({
          id: randomUUID(),
          kind: 'result',
          title: `${exam.year} 年${exam.session ? ` ${exam.session}` : ''} 放榜`,
          start: exam.resultDate,
          end: exam.resultDate,
          at: '',
          endAt: '',
          complete: false,
          notes: '自动同步自专攻考试历史',
          replaces: '',
          sourceId,
          autoGenerated: true,
          syncEnabled: true,
          linkContact: false,
        });
      }
    }
  }

  // 清理已删除考试记录对应的自动生成事件
  const validSourcePrefixes = examHistory.map(
    (exam) => `major:${majorId}:exam:${exam.id}`,
  );
  timeline.events = timeline.events.filter((event) => {
    if (!event.autoGenerated || !event.sourceId) return true;
    return validSourcePrefixes.some((prefix) =>
      event.sourceId.startsWith(prefix),
    );
  });

  return data;
}

/**
 * 为所有想考的研究室同步专攻考试历史
 * 在专攻考试历史更新时调用
 */
export function syncAllLabsForMajor(data, majorId) {
  const labs = data.labs?.filter((lab) => lab.majorId === majorId) ?? [];

  for (const lab of labs) {
    syncExamsToTimeline(data, lab.id, majorId);
  }

  return data;
}

/**
 * 每次保存都要执行的实体默认值补全；新建实体也需要这些字段。
 * 不是只在启动时运行的一次性 schema 迁移。
 */
export function applyEntityDefaults(data) {
  data = addVersionControl(data);
  data = initializeTimelineSources(data);
  data = initializeAnalysisHistory(data);
  // A page opened before this version may still send untagged imported tasks.
  tagImportedTasks(data);
  return data;
}
