import { strict as assert } from 'node:assert';
import { describe, it } from 'node:test';

import {
  addVersionControl,
  applyEntityDefaults,
  initializeAnalysisHistory,
  initializeTimelineSources,
  syncExamsToTimeline,
} from './data-migrations.mjs';

describe('数据迁移测试', () => {
  it('应该为日程、材料待办和考试历史添加版本号', () => {
    const data = {
      version: 2,
      universities: [],
      schools: [],
      majors: [
        {
          id: 'major1',
          schoolId: 'school1',
          name: '测试专攻',
          examHistory: [{ id: 'exam1', year: '2024' }],
        },
      ],
      professors: [],
      labs: [
        {
          id: 'lab1',
          majorId: 'major1',
          name: '测试研究室',
          timeline: { events: [], hiddenSources: [] },
          tasks: [],
        },
      ],
    };

    const result = addVersionControl(data);

    assert.equal(result.labs[0].timeline.version, 0);
    assert.equal(result.labs[0].tasksVersion, 0);
    assert.equal(result.majors[0].examHistoryVersion, 0);
  });

  it('应该为现有日程事件标记为手动创建', () => {
    const data = {
      version: 2,
      universities: [],
      schools: [],
      majors: [],
      professors: [],
      labs: [
        {
          id: 'lab1',
          majorId: 'major1',
          name: '测试研究室',
          timeline: {
            events: [
              {
                id: 'event1',
                kind: 'interview',
                title: '面试',
                start: '2024-11-01',
                end: '2024-11-01',
                at: '',
                endAt: '',
                complete: false,
                notes: '',
                replaces: '',
              },
            ],
            hiddenSources: [],
          },
        },
      ],
    };

    const result = initializeTimelineSources(data);

    assert.equal(result.labs[0].timeline.events[0].autoGenerated, false);
    assert.equal(result.labs[0].timeline.events[0].syncEnabled, true);
    assert.equal(result.labs[0].timeline.autoSyncExams, true);
  });

  it('应该为专攻添加分析历史字段', () => {
    const data = {
      version: 2,
      universities: [],
      schools: [],
      majors: [{ id: 'major1', schoolId: 'school1', name: '测试专攻' }],
      professors: [],
      labs: [],
    };

    const result = initializeAnalysisHistory(data);

    assert.ok(Array.isArray(result.majors[0].analysisHistory));
    assert.equal(result.majors[0].analysisHistory.length, 0);
  });

  it('应该从专攻考试历史生成日程事件', () => {
    const data = {
      version: 2,
      universities: [],
      schools: [],
      majors: [
        {
          id: 'major1',
          schoolId: 'school1',
          name: '测试专攻',
          applicationStart: '2024-10-01',
          applicationEnd: '2024-10-31',
          examHistory: [
            {
              id: 'exam1',
              year: '2024',
              session: '秋季',
              writtenDate: '2024-11-15',
              interviewDate: '2024-11-25',
              resultDate: '2024-12-10',
              subjects: '数学、英语',
            },
          ],
        },
      ],
      professors: [],
      labs: [
        {
          id: 'lab1',
          majorId: 'major1',
          name: '测试研究室',
          timeline: { events: [], hiddenSources: [], autoSyncExams: true },
        },
      ],
    };

    const result = syncExamsToTimeline(data, 'lab1', 'major1');

    const events = result.labs[0].timeline.events;
    assert.ok(events.length > 0, '应该生成日程事件');

    const writtenEvent = events.find((e) => e.kind === 'written');
    assert.ok(writtenEvent, '应该有笔试事件');
    assert.equal(writtenEvent.start, '2024-11-15');
    assert.equal(writtenEvent.autoGenerated, true);
    assert.ok(
      writtenEvent.sourceId.includes('major:major1:exam:exam1:written'),
    );

    const interviewEvent = events.find((e) => e.kind === 'interview');
    assert.ok(interviewEvent, '应该有面试事件');
    assert.equal(interviewEvent.start, '2024-11-25');

    const resultEvent = events.find((e) => e.kind === 'result');
    assert.ok(resultEvent, '应该有放榜事件');
    assert.equal(resultEvent.start, '2024-12-10');
  });

  it('不应该覆盖用户手动创建的日程', () => {
    const data = {
      version: 2,
      universities: [],
      schools: [],
      majors: [
        {
          id: 'major1',
          schoolId: 'school1',
          name: '测试专攻',
          examHistory: [
            {
              id: 'exam1',
              year: '2024',
              writtenDate: '2024-11-15',
            },
          ],
        },
      ],
      professors: [],
      labs: [
        {
          id: 'lab1',
          majorId: 'major1',
          name: '测试研究室',
          timeline: {
            events: [
              {
                id: 'manual1',
                kind: 'written',
                title: '用户自定义笔试时间',
                start: '2024-11-16',
                end: '2024-11-16',
                at: '',
                endAt: '',
                complete: false,
                notes: '已改期',
                replaces: 'major:major1:exam:exam1:written',
                autoGenerated: false,
              },
            ],
            hiddenSources: [],
            autoSyncExams: true,
          },
        },
      ],
    };

    const result = syncExamsToTimeline(data, 'lab1', 'major1');

    const events = result.labs[0].timeline.events;
    // 应该只有一个笔试事件（用户手动创建的）
    const writtenEvents = events.filter((e) => e.kind === 'written');
    assert.equal(writtenEvents.length, 1);
    assert.equal(writtenEvents[0].start, '2024-11-16');
    assert.equal(writtenEvents[0].notes, '已改期');
  });

  it('应该按顺序应用所有迁移', () => {
    const data = {
      version: 2,
      universities: [],
      schools: [],
      majors: [{ id: 'major1', schoolId: 'school1', name: '测试专攻' }],
      professors: [],
      labs: [
        {
          id: 'lab1',
          majorId: 'major1',
          name: '测试研究室',
          timeline: { events: [], hiddenSources: [] },
          tasks: [],
        },
      ],
    };

    const result = applyEntityDefaults(data);

    // 验证版本控制
    assert.equal(result.labs[0].timeline.version, 0);
    assert.equal(result.labs[0].tasksVersion, 0);

    // 验证日程来源
    assert.equal(result.labs[0].timeline.autoSyncExams, true);

    // 验证分析历史
    assert.ok(Array.isArray(result.majors[0].analysisHistory));
  });
});
