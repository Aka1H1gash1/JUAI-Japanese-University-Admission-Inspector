export const snake = (value) =>
  value.replaceAll(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
export function sqlType(type) {
  if (type === 'AMOUNT' || type === 'BOOLEAN') return 'INTEGER';
  if (type === 'JSON') return 'TEXT';
  return type;
}
export function valueToSql(value, type) {
  if (
    value === undefined ||
    value === null ||
    (type === 'AMOUNT' && value === '')
  )
    return null;
  if (type === 'BOOLEAN' || type === 'AMOUNT') return Number(value);
  if (type === 'JSON') return JSON.stringify(value);
  return value;
}
export function valueFromSql(value, type) {
  if (value === null) {
    if (type === 'AMOUNT' || type === 'TEXT') return '';
    return undefined;
  }
  if (type === 'BOOLEAN') return !!value;
  if (type === 'AMOUNT') return String(value);
  if (type === 'JSON') return JSON.parse(value);
  return value;
}

export function encode(spec, object) {
  const known = new Set([
    'id',
    ...Object.keys(spec.columns),
    ...(spec.derived ?? []),
    ...(spec.children ?? []),
  ]);
  return {
    ...Object.fromEntries(
      Object.entries(spec.columns).map(([name, type]) => [
        snake(name),
        valueToSql(object[name], type),
      ]),
    ),
    present_json: JSON.stringify(
      Object.keys(object)
        .filter((key) => object[key] !== undefined)
        .toSorted(),
    ),
    extras_json: JSON.stringify(
      Object.fromEntries(
        Object.entries(object).filter(([key]) => !known.has(key)),
      ),
    ),
  };
}
export function decode(spec, row) {
  const extras = JSON.parse(row.extras_json);
  const result = {};
  for (const name of JSON.parse(row.present_json)) {
    if (name === 'id' && row.id !== undefined) result.id = row.id;
    else if (Object.hasOwn(spec.columns, name)) {
      const value = valueFromSql(row[snake(name)], spec.columns[name]);
      if (value !== undefined) result[name] = value;
    } else if (Object.hasOwn(extras, name)) result[name] = extras[name];
  }
  return result;
}

export function columnSql(name, type) {
  const column = snake(name);
  let check = '';
  if (type === 'BOOLEAN') check = ` CHECK (${column} IN (0, 1))`;
  if (type === 'AMOUNT') check = ` CHECK (${column} BETWEEN 0 AND 999999999)`;
  if (type === 'JSON')
    check = ` CHECK (${column} IS NULL OR json_valid(${column}))`;
  return `${column} ${sqlType(type)}${check}`;
}

// Compatibility JSON is a computed projection, not a stored source of truth.
export function jsonProjection(spec, extra = {}, prefix = '') {
  const pairs = ["'id'", `${prefix}id`];
  for (const [name, type] of Object.entries(spec.columns)) {
    const col = `${prefix}${snake(name)}`;
    let expression = col;
    if (type === 'BOOLEAN')
      expression = `json(CASE WHEN ${col} IS NULL THEN 'null' WHEN ${col}=1 THEN 'true' ELSE 'false' END)`;
    if (type === 'JSON') expression = `json(${col})`;
    if (Object.hasOwn(extra, name)) expression = extra[name];
    pairs.push(`'${name}'`, expression);
  }
  for (const [name, expression] of Object.entries(extra).filter(
    ([name]) => !Object.hasOwn(spec.columns, name),
  ))
    pairs.push(`'${name}'`, expression);
  return `json_patch(${prefix}extras_json, json_object(${pairs.join(',')}))`;
}
